def normalize_key(location: str) -> str:
    """G 列 (都道府県 市区町村 [区] [町域]) から AREA_NOTES のキーを返す."""
    parts = location.split()
    if len(parts) < 2:
        raise ValueError(f"unexpected location: {location!r}")
    city = parts[1]
    # 政令市の区 / 郡の町村 は 3 番目まで含める
    if len(parts) >= 3 and (parts[2].endswith("区") or parts[1].endswith("郡")):
        return city + parts[2]
    return city


def lookup(location: str) -> AreaNote:
    if location in FULL_KEY_NOTES:
        return FULL_KEY_NOTES[location]
    key = normalize_key(location)
    if key in AREA_NOTES:
        return AREA_NOTES[key]
    # 郡だけで町村が無い場合 (例: 埼玉県 児玉郡)
    parts = location.split()
    if parts[1] in AREA_NOTES:
        return AREA_NOTES[parts[1]]
    raise KeyError(f"area note missing for {location!r} (key={key})")


def city_label(location: str) -> str:
    """職種名の重複解消や本文で使う「市区町村」表記 (例: 北九州市小倉北区, 糸島市)."""
    parts = location.split()
    if len(parts) >= 3 and parts[2].endswith("区"):
        return parts[1] + parts[2]
    if len(parts) >= 3 and parts[1].endswith("郡"):
        return parts[2]
    return parts[1]


def prefecture(location: str) -> str:
    return location.split()[0]
