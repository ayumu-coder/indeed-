def build_appeal(i: int) -> str:
    # 4 × 5 × 5 = 100 通り。i = a + 4b + 20c と分解して全行で別の組み合わせにする
    head = APPEAL_HEAD[i % 4]
    points = APPEAL_POINTS[(i // 4) % 5]
    fit = APPEAL_FIT[(i // 20) % 5]
    body = [head, ""]
    for title, text in points:
        body += [f"✅ {title}", text, ""]
    body += ["＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼向いている方✼》", ""]
    body += fit
    body += ["", "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼応募について✼》", ""]
    body += APPEAL_NOTE
    return "\n".join(body)


def main() -> int:
    rows = [["駅名", "住所", "キャッチコピー", "タイトル", "仕事内容", "アピールポイント"]]
    for i, (station, address, _op, _ok) in enumerate(STATIONS):
        area = area_of(address)
        catch = f"{CATCH_LEAD[i % 10]}◎{CATCH_MID[(i // 10) % 10]}{CATCH_TAIL[i % 4]}"
        title = f"{TITLE_HEAD[i % 5]}｜{TITLE_JOB[(i // 5) % 4]}｜{station}駅エリア"
        if width(title) > 30:
            # 駅名が長い行は接頭辞と職種表現を詰める。全角 30 を超えると
            # スマホの検索結果で駅名まで届かない
            title = f"未経験OK｜検品・梱包｜{station}駅"
        rows.append([station, address, catch, title,
                     build_body(i, station, address, area), build_appeal(i)])

    with OUT.open('w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f).writerows(rows)

    cols = {name: [r[k] for r in rows[1:]] for k, name in
            enumerate(('駅名', '住所', 'キャッチコピー', 'タイトル', '仕事内容', 'アピールポイント'))}
    print(f'{len(rows)-1} 行')
    for name in ('キャッチコピー', 'タイトル', '仕事内容', 'アピールポイント'):
        print(f'  {name}: ユニーク {len(set(cols[name]))} / {len(cols[name])}')
    print(f'  タイトル幅 {min(map(width, cols["タイトル"])):.0f}〜{max(map(width, cols["タイトル"])):.0f} 全角')
    print(f'  キャッチ幅 {min(map(width, cols["キャッチコピー"])):.0f}〜{max(map(width, cols["キャッチコピー"])):.0f} 全角')
    return 0


if __name__ == '__main__':
    sys.exit(main())
