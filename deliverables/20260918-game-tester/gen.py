    i = 0
    for pref, entries in STATIONS.items():
        for station, address, _op, _ok in entries:
            rows.append([
                pref,
                station,
                address,
                CATCH[i % len(CATCH)],
                f"未経験OK｜ゲームテスター｜{station}駅エリア",
                BODY[i % len(BODY)].format(station=station, address=address, area=area_of(address, pref)),
                APPEAL,
            ])
            i += 1
    with OUT.open('w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f).writerows(rows)

    titles = [r[4] for r in rows[1:]]
    print(f'{len(rows)-1} 行 / {len(STATIONS)} 都道府県')
    print(f'タイトル幅 {min(map(width, titles)):.0f}〜{max(map(width, titles)):.0f} 全角')
    print(f'キャッチ幅 {min(map(width, CATCH)):.0f}〜{max(map(width, CATCH)):.0f} 全角 / {len(CATCH)} パターン')
    print(f'仕事内容 {len(BODY)} パターン / ユニーク {len({r[5] for r in rows[1:]})} 種')
    return 0


