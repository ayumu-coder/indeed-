def area_of(address: str, pref: str) -> str:
    """都道府県＋市区町村。町名は落とす。"""
    rest = address[len(pref):]
    for marker in ('市', '区', '町', '村'):
        pass
    # 「◯◯市◯◯区」まで拾い、なければ「◯◯市」「◯◯郡◯◯町」まで
    import re
    m = re.match(r'(.+?市.+?区|.+?郡.+?[町村]|.+?[市町村])', rest)
    return pref + (m.group(1) if m else rest)


