def build_body(job: str, i: int, ward: str, station: str, address: str) -> str:
    spec = JOBS[job]
    l1, l2 = spec["hook"][i % 4]
    a1, a2, ans = spec["ask"][(i // 4) % 4]
    steps = spec["steps"][(i // 2) % 3]
    support = spec["support"][(i // 3) % 3]
    close = BODY_CLOSE[(i // 5) % 4]
    return "\n".join([
        "✦・━━━━━━━━━━━━━━━・✦",
        f"＼東京都{ward}で募集中／", l1, l2,
        "✦・━━━━━━━━━━━━━━━・✦",
        "", a1, a2, "", ans, "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✧お仕事の内容✧】", "",
        "\n\n".join(steps), "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✨はじめての方へ✨】", "",
        "\n".join(support), "",
        spec["note"], "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✧勤務地✧】", "",
        f"{address}（{station}駅エリア）", "",
        "給与・勤務時間・シフトなどの詳細は、",
        "ご応募後にあらためてご案内します。", close,
    ])


def build_appeal(job: str, i: int) -> str:
    spec = JOBS[job]
    # 4 × 3 × 2 = 24 通り。i = a + 4b + 12c と分解して 23 行すべて別にする
    head = APPEAL_HEAD[i % 4]
    points = spec["appeal_points"][(i // 4) % 3]
    fit = spec["fit"][(i // 12) % 2]
    body = [head, ""]
    for title, text in points:
        body += [f"✅ {title}", text, ""]
    body += ["＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼向いている方✼》", ""] + fit
    body += ["", "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼応募について✼》", ""] + APPEAL_NOTE
    return "\n".join(body)


def main() -> int:
    rows = [["区", "職種", "駅名", "住所", "キャッチコピー", "タイトル", "仕事内容", "アピールポイント"]]
    for job, spec in JOBS.items():
        for i, (ward, station, address, _ok) in enumerate(WARDS):
            catch = (f"{spec['catch_lead'][i % 5]}◎"
                     f"{spec['catch_mid'][(i // 5) % 5]}{CATCH_TAIL[i % 5]}")
            title = f"{TITLE_HEAD[i % 4]}｜{spec['title_job'][(i // 4) % 4]}｜{ward}"
            rows.append([ward, job, station, address, catch, title,
                         build_body(job, i, ward, station, address),
                         build_appeal(job, i)])

    with OUT.open('w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f).writerows(rows)

    cols = {name: [r[k] for r in rows[1:]] for k, name in enumerate(rows[0])}
    print(f'{len(rows)-1} 行 / {len(JOBS)} 職種 × {len(WARDS)} 区')
    for name in ('キャッチコピー', 'タイトル', '仕事内容', 'アピールポイント'):
        print(f'  {name}: ユニーク {len(set(cols[name]))} / {len(cols[name])}')
    print(f'  タイトル幅 {min(map(width, cols["タイトル"])):.0f}〜{max(map(width, cols["タイトル"])):.0f} 全角')
    print(f'  キャッチ幅 {min(map(width, cols["キャッチコピー"])):.0f}〜{max(map(width, cols["キャッチコピー"])):.0f} 全角')
    return 0


