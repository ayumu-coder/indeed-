def width(s: str) -> float:
    return sum(2 if unicodedata.east_asian_width(c) in 'WFA' else 1 for c in s) / 2


def city_of(address: str) -> str:
    m = re.match(r'(愛知県.+?市.+?区|愛知県.+?郡.+?[町村]|愛知県.+?[市町村])', address)
    return (m.group(1) if m else address).replace('愛知県', '')


def area_of(address: str) -> str:
    return '愛知県' + city_of(address)


