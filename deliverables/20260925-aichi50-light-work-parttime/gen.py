def build_appeal(i: int) -> str:
    # 5 × 5 × 2 = 50 通り。i = a + 5b + 25c と分解して全行を別にする
    head = APPEAL_HEAD[i % 5]
    points = APPEAL_POINTS[(i // 5) % 5]
    fit = APPEAL_FIT[(i // 25) % 2]
    body = [head, ""]
    for title, text in points:
        body += [f"✅ {title}", text, ""]
    body += ["＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼向いている方✼》"] + fit
    body += ["", "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼応募について✼》"] + APPEAL_NOTE
    return "\n".join(body)


def main() -> int:
    rows = [["区/市", "職種", "駅名", "住所", "キャッチコピー", "タイトル", "仕事内容", "アピールポイント"]]
    for i, (_rank, station, address, _op, _ok) in enumerate(STATIONS):
        catch = f"{CATCH_LEAD[i % 10]}◎{CATCH_MID[(i // 10) % 5]}{CATCH_TAIL[i % 5]}"
        title = f"{TITLE_HEAD[i % 5]}｜{TITLE_JOB[(i // 5) % 4]}｜{station}駅エリア"
        if width(title) > 30:
            title = f"未経験から｜軽作業｜{station}駅"
        rows.append([city_of(address), JOB, station, address, catch, title,
                     build_body(i, station, address, area_of(address)), build_appeal(i)])

    with OUT.open('w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f).writerows(rows)

    cols = {n: [r[k] for r in rows[1:]] for k, n in enumerate(rows[0])}
    print(f'{len(rows)-1} 行')
    for n in ('キャッチコピー', 'タイトル', '仕事内容', 'アピールポイント'):
        print(f'  {n}: ユニーク {len(set(cols[n]))} / {len(cols[n])}')
    print(f'  タイトル幅 {min(map(width, cols["タイトル"])):.0f}〜{max(map(width, cols["タイトル"])):.0f} 全角')
    print(f'  キャッチ幅 {min(map(width, cols["キャッチコピー"])):.0f}〜{max(map(width, cols["キャッチコピー"])):.0f} 全角')
    return 0


