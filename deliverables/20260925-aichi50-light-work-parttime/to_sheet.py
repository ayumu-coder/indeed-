# -*- coding: utf-8 -*-
"""納品 CSV を Indeed の 67 列シートに写して lint_sheet.py を通すためのブリッジ。

lint_sheet.py は 67 列シート専用なので、こちらの 8 列をそのまま渡せない。
ハウスルール（copy-wage / title-word / bullet-spacing）は職種名・キャッチコピー・
仕事内容・アピールポイントの 4 列だけを見るため、その 4 列を写せば判定できる。
会社名・給与などはこの納品物が持たない情報なので空のままにする
（その結果 required などの検出が出るが、それは列が無いことによるもの）。
"""
import csv, pathlib, sys

SRC = pathlib.Path('愛知50駅_軽作業スタッフ_アルバイトパート週5フルタイム_20260925.csv')
DST = pathlib.Path('_as_sheet.csv')
HEADER = ['ステータス', '会社名', '職種名', '職業カテゴリー', '求人キャッチコピー',
          '勤務地（郵便番号）', '勤務地（都道府県・市区町村・町域）', '勤務地（丁目・番地・号）',
          '勤務地（建物名・階数）', '雇用形態', '有料職業紹介に該当', '給与形態', '給与（最低額）',
          '給与（最高額）', '給与（表示形式）', '固定残業代の有無', '固定残業代（最低額）',
          '固定残業代（最高額）', '固定残業代（支払い単位）', '固定残業代（時間）', '固定残業代（分）',
          '固定残業代（超過分の追加支払への同意）', '勤務形態', '平均所定労働時間',
          '平均所定労働時間（分）', '社会保険', '社会保険（適用されない理由）', '試用期間の有無',
          '試用期間（期間）', '試用期間（期間の単位）', '試用期間（試用期間中の労働条件）',
          '試用期間中の給与形態', '試用期間中の給与（最低額）', '試用期間中の給与（最高額）',
          '試用期間中の給与（表示形式）', '試用期間中の固定残業代の有無',
          '試用期間中の固定残業代（最低額）', '試用期間中の固定残業代（最高額）',
          '試用期間中の固定残業代（支払い単位）', '試用期間中の固定残業代（時間）',
          '試用期間中の固定残業代（分）', '試用期間中の固定残業代（超過分の追加支払への同意）',
          '試用期間中の平均所定労働時間', '試用期間中の平均所定労働時間（分）',
          '試用期間中のその他の条件', '募集要項（仕事内容）', '募集要項（アピールポイント）',
          '募集要項（求める人材）', '募集要項（勤務時間・曜日）', '募集要項（休暇・休日）',
          '募集要項（勤務地の補足）', '募集要項（アクセス）', '募集要項（給与の補足）',
          '募集要項（待遇・福利厚生）', '募集要項（その他）', '掲載画像', 'タグ', '採用予定人数',
          '履歴書の有無', '応募者に関する情報', '応募用メールアドレス',
          '求人問い合わせ先電話番号（半角）', '審査用の質問', '自動アプローチ利用設定',
          '自動アプローチ条件設定', 'ユーザー指定ID']


def main() -> int:
    with SRC.open(encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))
    out = [HEADER]
    for r in rows:
        blank = {c: '' for c in HEADER}
        blank['職種名'] = r['タイトル']
        blank['求人キャッチコピー'] = r['キャッチコピー']
        blank['募集要項（仕事内容）'] = r['仕事内容']
        blank['募集要項（アピールポイント）'] = r['アピールポイント']
        blank['勤務地（都道府県・市区町村・町域）'] = r['住所']
        blank['会社名'] = '（この納品物には含まれない）'
        out.append([blank[c] for c in HEADER])
    with DST.open('w', encoding='utf-8', newline='') as f:
        csv.writer(f).writerows(out)
    print(f'{len(out)-1} 行を 67 列シートに写した: {DST}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
