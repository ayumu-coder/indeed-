def build_appeal(i: int) -> str:
    # 6 × 5 × 5 = 150 通り。i = a + 6b + 30c と分解して全 150 行を別にする
    head = APPEAL_HEAD[i % 6]
    points = APPEAL_POINTS[(i // 6) % 5]
    fit = APPEAL_FIT[(i // 30) % 5]
    body = [head, ""]
    for title, text in points:
        body += [f"✅ {title}", text, ""]
    body += [RULE, "《◆向いている方◆》"] + fit
    body += ["", RULE, "《◆応募について◆》"] + APPEAL_NOTE
    return "\n".join(body)


def build_rows(stations, offset: int):
    rows = []
    for n, entry in enumerate(stations):
        _rank, station, address = entry[0], entry[1], entry[2]  # (順位, 駅名, 住所, 事業者, 町名確度, 乗降人員)
        i = offset + n
        city = city_of(address)
        catch = f"{CATCH_LEAD[i % 10]}◇{CATCH_MID[(i // 10) % 15]}{CATCH_TAIL[i % 5]}"
        title = f"{TITLE_HEAD[i % 5]}｜{TITLE_JOB[(i // 5) % 5]}｜{station}駅エリア"
        if width(title) > 30:
            title = f"はじめてでも｜検品・梱包｜{station}駅"
        rows.append([city, JOB, station, address, catch, title,
                     build_body(i, station, address, city), build_appeal(i)])
    return rows


def dump(path, rows):
    with path.open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(rows)


def main() -> int:
    gifu = build_rows(GIFU, 0)
    hiroshima = build_rows(HIROSHIMA, 50)
    mie_shiga = build_rows(MIE_SHIGA, 100)
    dump(OUT_GIFU, gifu)
    dump(OUT_HIROSHIMA, hiroshima)
    dump(OUT_MIE_SHIGA, mie_shiga)
    allrows = gifu + hiroshima + mie_shiga
    dump(OUT_ALL, allrows)

    cols = {n: [r[k] for r in allrows] for k, n in enumerate(HEADER)}
    print(f'岐阜 {len(gifu)} 行 / 広島 {len(hiroshima)} 行 / 三重滋賀 {len(mie_shiga)} 行 / 結合 {len(allrows)} 行')
    for n in ('駅名', 'キャッチコピー', 'タイトル', '仕事内容', 'アピールポイント'):
        print(f'  {n}: ユニーク {len(set(cols[n]))} / {len(cols[n])}')
    print(f'  タイトル幅 {min(map(width, cols["タイトル"])):.0f}〜{max(map(width, cols["タイトル"])):.0f} 全角')
    print(f'  キャッチ幅 {min(map(width, cols["キャッチコピー"])):.0f}〜{max(map(width, cols["キャッチコピー"])):.0f} 全角')
    return 0


