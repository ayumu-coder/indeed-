def build_body(i: int, pref: str, station: str, address: str, city: str) -> str:
    # 55 = 11 × 5 なので、行を決める自由度は (r, q) = (i % 5, i // 5) の 2 つしかない。
    # 6 つのブロックに (r + k·q) mod 5 という互いに異なる一次式を割り当てると、
    # 任意の 2 行で一致するブロックが必ず 1 個以下になる（k が 1 つに定まるため）。
    # 単純な i // 2, i // 3 のような取り方だと周期が重なり、本文が 75% 一致していた。
    r, q = i % 5, i // 5
    l1, l2 = HOOK[r]
    a1, a2, ans = ASK[q % 5]
    steps = STEPS[(r + q) % 5]
    private = (PRIVATE_SOFT if STRICT else PRIVATE_STRICT)[(r + 2 * q) % 5]
    support = SUPPORT[(r + 3 * q) % 5]
    close = CLOSE[(r + 4 * q) % 5]
    return "\n".join([
        "✦・━━━━━━━━━━━━━━━・✦",
        f"＼{city}で募集中／", l1, l2,
        "✦・━━━━━━━━━━━━━━━・✦",
        "", a1, a2, "", ans, "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✧お仕事の内容✧】",
        "\n".join(steps), "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✨プライベートとの両立✨】",
        "\n".join(private), "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✨はじめての方へ✨】",
        "\n".join(support), "",
        "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝",
        "【✧勤務地✧】", "",
        f"{address}（{station}駅エリア）", "",
        "給与・勤務時間・シフトなどの詳細は、",
        "ご応募後にあらためてご案内します。", close,
    ])


def build_appeal(i: int) -> str:
    # 本文と同じ考え方で (r, q) の一次式に割り当てる。5 × 6 × 2 = 60 通り。
    r, q = i % 5, i // 5
    # (r, q % 6, q // 6) は q が 0〜10 なので 55 行すべてで異なる組になる。
    # 一次式にすると衝突して 34 通りに落ちたため、こちらを使う。
    head = APPEAL_HEAD[r]
    points = APPEAL_POINTS[q % 6]
    fit = APPEAL_FIT[q // 6]
    body = [head, ""]
    for title, text in points:
        body += [f"✅ {title}", text, ""]
    body += ["＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼向いている方✼》"] + fit
    body += ["", "＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝", "《✼応募について✼》"] + APPEAL_NOTE
    return "\n".join(body)


def main() -> int:
    rows = []
    i = 0
    for pref in ORDER:
        for station, address, _op, _ok in STATIONS[pref]:
            city = city_of(address)
            catch = f"{CATCH_LEAD[i % 11]}◎{CATCH_MID[(i // 11) % 5]}{CATCH_TAIL[i % 5]}"
            head = primary_station(station)
            title = f"{TITLE_HEAD[i % 5]}｜{TITLE_JOB[(i // 5) % 4]}｜{head}駅エリア"
            if width(title) > 30:
                title = f"未経験から｜一般事務｜{head}駅"
            rows.append([city, JOB, station, address, catch, title,
                         build_body(i, pref, station, address, city), build_appeal(i)])
            i += 1

    with OUT.open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(rows)

    cols = {n: [r[k] for r in rows] for k, n in enumerate(HEADER)}
    print(f'{len(rows)} 行 / {len(ORDER)} 都道府県 × 5 駅')
    for n in ('キャッチコピー', 'タイトル', '仕事内容', 'アピールポイント'):
        print(f'  {n}: ユニーク {len(set(cols[n]))} / {len(cols[n])}')
    print(f'  タイトル幅 {min(map(width, cols["タイトル"])):.0f}〜{max(map(width, cols["タイトル"])):.0f} 全角')
    print(f'  キャッチ幅 {min(map(width, cols["キャッチコピー"])):.0f}〜{max(map(width, cols["キャッチコピー"])):.0f} 全角')
    return 0


if __name__ == '__main__':
    sys.exit(main())
