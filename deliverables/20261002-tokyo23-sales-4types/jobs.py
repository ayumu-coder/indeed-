# -*- coding: utf-8 -*-
"""4 つの営業職の文面プール。

各プールは 5 要素。本文は (r, q) = (w % 5, w // 5) の一次式で選ぶので、
同一職種の 23 行で一致するブロックは必ず 1 個以下になる（gen.py 参照）。

**定義上言えることと、事業者ごとに違うことを分けている。**
- ルート営業の「既存のお客様が中心」、反響営業の「問い合わせからの対応」は職種の定義。
  したがって反響営業では「テレアポ・飛び込みはありません」と書ける。
- 新規開拓営業の手法（反響／紹介／訪問／電話）は事業者ごとに違う。
  したがって「飛び込みなし」とは書かない。
- モバイル営業の販路（店舗の来店型か法人訪問か）も事業者ごとに違う。
  したがって商材とヒアリングの話に寄せ、販路を断定しない。
- ノルマ・インセンティブ・直行直帰・社用車の有無はすべて事業者ごと。断定しない。
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class JobSpec:
    key: str
    name: str                      # 職種列に入れる名称
    title_labels: tuple[str, ...]  # タイトルの職種表現
    catch_lead: tuple[str, ...]
    catch_mid: tuple[str, ...]
    hooks: tuple[tuple[str, str], ...]
    asks: tuple[tuple[str, str, str], ...]
    steps: tuple[tuple[str, ...], ...]
    merits: tuple[tuple[str, ...], ...]
    appeal_heads: tuple[str, ...]
    appeal_points: tuple[tuple[tuple[str, str], ...], ...]


