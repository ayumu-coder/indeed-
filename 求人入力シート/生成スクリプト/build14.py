def load(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.reader(f))
    return rows[0], [dict(zip(rows[0], r)) for r in rows[1:]]


def dump(path, header, records):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=header, extrasaction="ignore")
        w.writeheader()
        for d in records:
            w.writerow({k: d.get(k, "") for k in header})


def company_slug(record):
    return record["会社名"].strip() or "社名掲載不可_税務会計3職種"


def main():
    header, records = load(SRC)
    records = records + [CM_QA] + MS_ROWS

    for rec in records:
        for ng in BANNED:
            if any(ng in str(v) for v in rec.values()):
                raise SystemExit(f"掲載不可の語が混入: {ng} -> {rec['職種名']}")
        if MONEY.search(unicodedata.normalize("NFKC", rec["求人キャッチコピー"])):
            raise SystemExit(f"キャッチコピーに給与額: {rec['求人キャッチコピー']}")

    copies = [r["求人キャッチコピー"] for r in records]
    if len(set(copies)) != len(copies):
        raise SystemExit("キャッチコピーが重複しています")

    dump(OUT_ALL, header, records)
    for old in os.listdir(OUT_DIR):
        if old.endswith(".csv"):
            os.remove(os.path.join(OUT_DIR, old))
    groups = {}
    for r in records:
        groups.setdefault(company_slug(r), []).append(r)
    for slug, recs in groups.items():
        dump(os.path.join(OUT_DIR, f"求人入力シート_{slug}.csv"), header, recs)

    print(f"wrote {OUT_ALL} ({len(records)} rows)")
    for slug, recs in sorted(groups.items()):
        print(f"  会社別/求人入力シート_{slug}.csv ({len(recs)})")


if __name__ == "__main__":
    main()
