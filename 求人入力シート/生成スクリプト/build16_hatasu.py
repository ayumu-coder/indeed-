def verify(rows):
    body = [k for k in rows[0] if k.startswith("募集要項") and k != "募集要項（給与の補足）"]
    no_money = body + ["職種名", "求人キャッチコピー"]
    for r in rows:
        for f in no_money:
            if MONEY.search(unicodedata.normalize("NFKC", r[f])):
                raise SystemExit(f"給与額が混入: {f} / {r['職種名']}")
        for w in TITLE_BANNED:
            if w in r["職種名"]:
                raise SystemExit(f"職種名に禁止語「{w}」: {r['職種名']}")
        for f in body + ["募集要項（給与の補足）"]:
            if re.search(r"[■✔][^\n]*\n\n[■✔]", r[f]):
                raise SystemExit(f"■/✔ 項目間に空行: {f} / {r['職種名']}")
        for ng in FORBIDDEN:
            for k, v in r.items():
                if ng in str(v):
                    raise SystemExit(f"掲載不可の語「{ng}」: {k} / {r['職種名']}")
    for key in ("職種名", "求人キャッチコピー"):
        vals = [r[key] for r in rows]
        if len(set(vals)) != len(vals):
            raise SystemExit(f"{key} が重複しています")


def main():
    header, rows = build()
    verify(rows)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT_CSV, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=header, extrasaction="raise")
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in header})
    print(f"wrote {os.path.normpath(OUT_CSV)} ({len(rows)} rows / {len(header)} cols)")
    for r in rows:
        print("  -", r["職種名"])


if __name__ == "__main__":
    main()
